#!/usr/bin/env node
/**
 * gen-labs.js — the single source of truth for the graded labs.
 *
 * Reads the PLAINTEXT lab sources in tools/_labs-src/lab-NN.js, verifies every
 * problem headlessly, seals each solution, and writes:
 *   labs/lab-NN.js     one manifest per lab (sealed solutions — never hand-edit)
 *   labs/index.js      the generated id list + getLab()
 *   labs/index.html    the static lab list (between the GENERATED markers)
 *
 *   node tools/gen-labs.js            verify + write
 *   node tools/gen-labs.js --check    verify only (exit 1 on any failure)
 *   node tools/gen-labs.js lab-02     limit to the named lab(s)
 *
 * Verification per problem (Node runner, the same one tools/grade.js uses):
 *   - the solution runs without errors and every check returns a value;
 *   - the solution passes against itself (sanity for nondeterministic checks);
 *   - the starter does NOT already pass.
 *
 * Why `_labs-src`: GitHub Pages' default (Jekyll) build does not publish files
 * or folders whose names start with "_", so the plaintext answers stay in the
 * repo for the teacher but off the public site. Don't add a .nojekyll file
 * without moving them.
 *
 * Source module shape (export default):
 *   { id, title, lesson, lessonTitle, intro?,
 *     problems: [{ key, title, points, prompt, starter, solution, checks,
 *                  runner?, html?, logs?, hint?, timeout?, loopBudget? }] }
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { sealSolution, grade } from "../jsrunner.js";
import { runInNode } from "./node-runner.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "tools", "_labs-src");
const OUT = join(ROOT, "labs");

const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const only = args.filter(a => !a.startsWith("--"));

function dedent(s) {
  const lines = String(s).replace(/^\n+/, "").replace(/\s+$/, "").split("\n");
  const widths = lines.filter(l => l.trim()).map(l => l.match(/^ */)[0].length);
  const min = widths.length ? Math.min(...widths) : 0;
  return lines.map(l => l.slice(min)).join("\n");
}

async function verifyProblem(lab, p) {
  const opts = { runner: p.runner || (p.html != null ? "frame" : "worker"), html: p.html || "",
    checks: p.checks || [], loopBudget: p.loopBudget || 1500,
    mock: p.mock || null, storage: p.storage || null, node: !!p.node, jsx: !!p.jsx, libs: p.libs || [] };
  const where = `${lab.id}/${p.key}`;
  const problems = [];
  const ref = await runInNode(p.solution, opts);
  if (ref.errors.length) problems.push(`${where}: solution errors: ${ref.errors.join("; ")}`);
  ref.checks.forEach((c, i) => {
    if (!c) problems.push(`${where}: check ${i + 1} did not run for the solution`);
    else if (!c.ok && !p.checks[i].expectError) problems.push(`${where}: check ${i + 1} threw for the solution: ${c.error}`);
  });
  const again = await runInNode(p.solution, opts);
  if (!grade(again, ref, opts.checks, { logs: !!p.logs }).passed) problems.push(`${where}: solution does not match itself (nondeterministic?)`);
  const start = await runInNode(p.starter ?? "", opts);
  if (grade(start, ref, opts.checks, { logs: !!p.logs }).passed) problems.push(`${where}: starter already passes`);
  if (!opts.checks.length && !p.logs) problems.push(`${where}: no checks and logs:false — nothing to grade`);
  return problems;
}

function manifestFor(lab) {
  const out = {
    id: lab.id, title: lab.title, lesson: lab.lesson, lessonTitle: lab.lessonTitle,
    intro: lab.intro ? dedent(lab.intro) : "",
    points: lab.problems.reduce((s, p) => s + p.points, 0),
    problems: lab.problems.map(p => {
      const q = { key: p.key, title: p.title, points: p.points, prompt: dedent(p.prompt),
        starter: dedent(p.starter ?? ""), checks: p.checks || [] };
      if (p.mock) q.mock = typeof p.mock === "function" ? p.mock.toString() : p.mock;
      for (const k of ["runner", "html", "logs", "hint", "timeout", "loopBudget", "height", "storage", "node", "jsx", "libs"])
        if (p[k] != null) q[k] = typeof p[k] === "string" && (k === "html" || k === "hint") ? dedent(p[k]) : p[k];
      q.solution = sealSolution(dedent(p.solution));
      return q;
    }),
  };
  return `// GENERATED by tools/gen-labs.js from tools/_labs-src/${lab.id}.js — do not edit.\n` +
    `// The solution strings are sealed (see jsrunner.js sealSolution).\n` +
    `export default ${JSON.stringify(out, null, 2)};\n`;
}

function indexJs(labs) {
  const list = labs.map(l => `  { id: ${JSON.stringify(l.id)}, title: ${JSON.stringify(l.title)}, lesson: ${JSON.stringify(l.lesson)}, problems: ${l.problems.length} },`).join("\n");
  return `// GENERATED by tools/gen-labs.js — do not edit.\n` +
    `/** Every lab, in course order. */\n` +
    `export const labs = [\n${list}\n];\n\n` +
    `/**\n * Load one lab manifest by id (e.g. "lab-02"), or null if unknown.\n * @param {string} id\n */\n` +
    `export async function getLab(id) {\n` +
    `  if (!labs.some(l => l.id === id)) return null;\n` +
    `  return (await import(\`./\${id}.js\`)).default;\n}\n`;
}

function indexHtmlList(labs) {
  return labs.map(l => {
    const n = l.id.slice(4);
    return `      <li><a href="./lab.html?id=${l.id}"><span class="num">${n}</span><span class="body">\n` +
      `        <div class="title">${l.title}</div>\n` +
      `        <div class="desc">${l.problems.length} problems · ${l.problems.reduce((s, p) => s + p.points, 0)} points · practises lesson ${n}</div></span></a></li>`;
  }).join("\n");
}

const files = readdirSync(SRC).filter(f => /^lab-\d\d\.js$/.test(f)).sort();
const labs = [];
for (const f of files) labs.push((await import(pathToFileURL(join(SRC, f)).href)).default);
const targets = only.length ? labs.filter(l => only.includes(l.id)) : labs;

let failures = 0;
for (const lab of targets) {
  const problems = [];
  for (const p of lab.problems) problems.push(...await verifyProblem(lab, { ...p, solution: dedent(p.solution) }));
  if (problems.length) {
    failures += problems.length;
    for (const msg of problems) console.error("✗ " + msg);
  } else {
    console.log(`✓ ${lab.id} — ${lab.problems.length} problems verified`);
  }
  if (!checkOnly && !problems.length) writeFileSync(join(OUT, `${lab.id}.js`), manifestFor(lab));
}

if (!checkOnly) {
  writeFileSync(join(OUT, "index.js"), indexJs(labs));
  const htmlPath = join(OUT, "index.html");
  if (existsSync(htmlPath)) {
    const html = readFileSync(htmlPath, "utf8");
    const next = html.replace(/(<!-- GENERATED:labs -->)[\s\S]*?(\n[ \t]*<!-- \/GENERATED:labs -->)/, `$1\n${indexHtmlList(labs)}$2`);
    writeFileSync(htmlPath, next);
  }
}
if (failures) {
  console.error(`${failures} problem(s) failed verification${checkOnly ? "" : " — those labs were not written"}.`);
  process.exit(1);
}
